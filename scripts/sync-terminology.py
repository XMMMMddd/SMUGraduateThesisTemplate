#!/usr/bin/env python3
"""Validate/export the terminology bank, or sync a template from its source."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import tempfile

REPOSITORY = "https://gitee.com/jiahaomai152XMMMM/biostatistics-terminology-bank.git"
PAGE = REPOSITORY.removesuffix(".git")
LOCK = ".academic-writing-terms.source.json"
ROOT = Path(__file__).resolve().parent.parent
MAX_BYTES = 2_000_000


def validate(path):
    data = path.read_bytes()
    if len(data) > MAX_BYTES:
        raise ValueError(f"词库超过 2 MB：{path}")
    value = json.loads(data.decode("utf-8-sig"))
    if not isinstance(value, dict) or set(value) - {"terms", "reviewId"}:
        raise ValueError(f"无效词库对象：{path}")
    terms = value.get("terms")
    if not isinstance(terms, list) or len(terms) > 5000:
        raise ValueError(f"terms 必须为不超过 5000 项的数组：{path}")
    if "reviewId" in value and (not isinstance(value["reviewId"], str) or not value["reviewId"].strip()):
        raise ValueError("reviewId 必须是非空字符串")
    seen = set()
    for entry in terms:
        if not isinstance(entry, dict) or set(entry) - {"canonical", "allowed", "forbidden", "variants", "reason"}:
            raise ValueError("无效词条字段")
        forms = [entry.get("canonical")]
        for key in ("allowed", "forbidden", "variants"):
            if key in entry and not isinstance(entry[key], list):
                raise ValueError(f"{key} 必须为字符串数组")
            forms.extend(entry.get(key, []))
        for form in forms:
            if not isinstance(form, str) or not form.strip() or "\n" in form or "\r" in form:
                raise ValueError("名称必须是非空单行字符串")
            if form in seen:
                raise ValueError(f"重复或冲突的表达：{form}")
            seen.add(form)
        if "reason" in entry and (not isinstance(entry["reason"], str) or not entry["reason"].strip()):
            raise ValueError("reason 必须为非空字符串")
    return value


def digest(data):
    return hashlib.sha256(data).hexdigest()


def revision(source):
    result = subprocess.run(["git", "-C", str(source), "rev-parse", "HEAD"], capture_output=True, text=True)
    return result.stdout.strip() if result.returncode == 0 else None


def markdown(value, english=False):
    title = "Biostatistics and genetic epidemiology terminology" if english else "医学统计与遗传流行病学术语表"
    notes = ["Generated by the terminology sync script. Edit the source JSON in the maintenance repository, then sync again.",
             "Allowed forms may coexist; forbidden forms require evidence; candidate variants are not confirmed synonyms.",
             "Review first use, language scope and conceptual boundaries in context."] if english else [
             "本文件由词库同步脚本生成。请在维护仓库修改 JSON 后重新同步。",
             "允许表达可以共存；禁用异写需有明确依据；待核实变体不代表已确认同义。",
             "首次定义、语言范围和概念边界须结合依据及正文语境核对。"]
    header = "| Standard name | Allowed forms | Forbidden forms | Candidate variants | Evidence and boundaries |" if english else "| 标准名称 | 允许表达 | 禁用异写 | 待核实变体 | 依据与边界 |"
    lines = [f"# {title}", "", f"Source: {PAGE}", "", *notes, "", header,
             "|---|---|---|---|---|"]
    def cell(text):
        return str(text).replace("|", "\\|").replace("\r", " ").replace("\n", "<br>")
    for item in value["terms"]:
        row = [item["canonical"], *["、".join(item.get(key, [])) or "—" for key in ("allowed", "forbidden", "variants")], item.get("reason", "—")]
        lines.append("| " + " | ".join(cell(part) for part in row) + " |")
    return ("\n".join(lines) + "\n").encode()


def outputs(source):
    zh, en = validate(source / "terms.json"), validate(source / "terms.en.json")
    return {".academic-writing-terms.json": (json.dumps(zh, ensure_ascii=False, indent=2) + "\n").encode(),
            "terminology.en.json": (json.dumps(en, ensure_ascii=False, indent=2) + "\n").encode(),
            "术语表.md": markdown(zh), "terminology.en.md": markdown(en, True)}


def sync(source, destination, force=False, check=False):
    files = outputs(source)  # Validate everything before writing anything.
    lock_path = destination / LOCK
    lock = json.loads(lock_path.read_text()) if lock_path.exists() else {}
    conflicts = []
    for name, data in files.items():
        target = destination / name
        if not target.exists() or target.read_bytes() == data:
            continue
        previous = lock.get("files", {}).get(name)
        # On first adoption only identical JSON profiles may be replaced; docs are derived.
        if (previous and digest(target.read_bytes()) != previous) or (not previous and name.endswith(".json")):
            conflicts.append(name)
    if conflicts and not force:
        raise ValueError("存在本地修改，未覆盖：" + "、".join(conflicts) + "。先同步回维护源，或使用 --force（会备份）。")
    if check:
        mismatches = [name for name, data in files.items() if not (destination / name).exists() or (destination / name).read_bytes() != data]
        expected_sources = {name: digest((source / name).read_bytes()) for name in ("terms.json", "terms.en.json")}
        if mismatches or lock.get("revision") != revision(source) or lock.get("repository") != PAGE or lock.get("sourceFiles") != expected_sources:
            raise ValueError("需要同步：" + "、".join(mismatches or [LOCK]))
        return
    destination.mkdir(parents=True, exist_ok=True)
    if conflicts:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
        for name in conflicts:
            shutil.copy2(destination / name, destination / f"{name}.terminology-backup-{stamp}")
    metadata = {"version": 1, "repository": PAGE, "revision": revision(source),
                "sourceFiles": {name: digest((source / name).read_bytes()) for name in ("terms.json", "terms.en.json")},
                "files": {name: digest(data) for name, data in files.items()}}
    files[LOCK] = (json.dumps(metadata, ensure_ascii=False, indent=2) + "\n").encode()
    for name, data in files.items():
        target = destination / name
        # Atomic replacement within the same filesystem.
        with tempfile.NamedTemporaryFile(dir=destination, delete=False) as handle:
            handle.write(data)
            temporary = Path(handle.name)
        try:
            temporary.replace(target)
        finally:
            temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="本地词库仓库；省略时从官方仓库克隆")
    parser.add_argument("--destination", type=Path, default=ROOT, help="模板根目录或导出目录")
    parser.add_argument("--validate", action="store_true", help="只校验源词库")
    parser.add_argument("--check", action="store_true", help="只核对是否与源一致")
    parser.add_argument("--force", action="store_true", help="备份后覆盖已有本地修改")
    args = parser.parse_args()
    def execute(source):
        if args.validate:
            for name in ("terms.json", "terms.en.json"):
                print(f"{name}: {len(validate(source / name)['terms'])} entries OK")
        else:
            sync(source, args.destination, args.force, args.check)
            print("词库校验通过。" if args.check else f"词库已同步至 {args.destination}")
    try:
        if args.source:
            execute(args.source.resolve())
        else:
            with tempfile.TemporaryDirectory(prefix="terminology-bank-") as temp:
                subprocess.run(["git", "clone", "--depth", "1", "--", REPOSITORY, temp], check=True, timeout=60)
                execute(Path(temp))
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        parser.exit(1, f"词库同步失败：{error}\n")


if __name__ == "__main__":
    main()
